// Writes src/ui/icon-data.ts: the inner SVG of every Phosphor icon the app names in src/ui/icons.tsx
// (`name: 'PhosphorName'` in ICON_NAMES), regular and bold only. The phone draws icons from these
// strings: the Phosphor package carries six weights per icon (a quarter of the start bundle).
//   node scripts/icons.mjs   (from mobile/, after adding an icon to ICON_NAMES)
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createElement } from 'react';
import { renderToStaticMarkup } from 'react-dom/server';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const src = readFileSync(path.join(root, 'src/ui/icons.tsx'), 'utf8');
const block = /export const ICON_NAMES = \{([\s\S]*?)\} as const;/.exec(src);
if (!block) throw new Error('ICON_NAMES not found in src/ui/icons.tsx');
const pairs = [...block[1].matchAll(/(\w+):\s*'(\w+)'/g)].map((m) => [m[1], m[2]]);

const inner = (svg) => svg.replace(/^<svg[^>]*>/, '').replace(/<\/svg>$/, '');
const lines = [];
for (const [name, phosphor] of pairs) {
  const mod = await import(`@phosphor-icons/react/dist/ssr/${phosphor}`);
  const C = mod[`${phosphor}Icon`] ?? mod[phosphor];
  if (!C) throw new Error(`No Phosphor icon ${phosphor}`);
  const regular = inner(renderToStaticMarkup(createElement(C, { weight: 'regular' })));
  const bold = inner(renderToStaticMarkup(createElement(C, { weight: 'bold' })));
  lines.push(`  ${name}: [${JSON.stringify(regular)}, ${JSON.stringify(bold)}],`);
}
writeFileSync(
  path.join(root, 'src/ui/icon-data.ts'),
  `// Generated by scripts/icons.mjs from @phosphor-icons/react (regular, bold). Do not edit: add the icon to ICON_NAMES in icons.tsx and run the script.\nexport const ICON_DATA = {\n${lines.join('\n')}\n} as const;\n`,
);
console.log(`icon-data.ts: ${pairs.length} icons`);
