/** The icon for a file or folder by its name: its type where one is known, else a plain page. */
export function fileIcon(name: string, dir = false): IconName {
  if (dir) return 'folder';
  const lower = name.toLowerCase();
  const named = BY_NAME[lower];
  if (named) return named;
  // Dotfiles are settings (.env, .gitignore, .npmrc, .env.local): one kind.
  if (lower.startsWith('.') && (lower.indexOf('.', 1) < 0 || lower.startsWith('.env.'))) return 'file-ini';
  const dot = lower.lastIndexOf('.');
  return (dot > 0 && BY_EXT[lower.slice(dot + 1)]) || 'file';
}
